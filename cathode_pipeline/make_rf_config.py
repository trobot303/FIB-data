"""Write config/workstation_rf.yaml for the random-forest segmented volumes found in a folder.

    python make_rf_config.py "D:\\microscopy\\Jehad\\FIB data\\segmented" [--out config/workstation_rf.yaml]
        [--device auto|cpu] [--tortuosity-downsample 2] [--grains-downsample 2]

Looks for processed_<sample>_segmented/{pore,LCO,LLZTO}_stack.tif (255 = phase), reads the
stack sizes, sets the common analysis volume to the smallest Z x 700 x 1700 and gives every
sample a crop that spans exactly that (centred in x/y, first Z slices).  Samples whose folder
is missing are skipped.
"""
import argparse
import re
from pathlib import Path

import tifffile
import yaml

SAMPLES = {"LCO50": 0.50, "LCO60": 0.60, "LCO60_2": 0.60, "LCO70": 0.70}
MASKS = {"pore": "pore_stack.tif", "lco": "LCO_stack.tif", "llzto": "LLZTO_stack.tif"}

ap = argparse.ArgumentParser()
ap.add_argument("data_root")
ap.add_argument("--out", default="config/workstation_rf.yaml")
ap.add_argument("--template", default="config/workstation_rf.yaml")
ap.add_argument("--device", default="auto")
ap.add_argument("--tortuosity-downsample", type=int, default=2)
ap.add_argument("--grains-downsample", type=int, default=2)
ap.add_argument("--n-workers", type=int, default=8)
a = ap.parse_args()

root = Path(a.data_root)
found = {}
for name in SAMPLES:
    d = root / f"processed_{name}_segmented"
    if not all((d / f).is_file() for f in MASKS.values()):
        print(f"skip {name}: {d} has no complete pore/LCO/LLZTO stacks")
        continue
    with tifffile.TiffFile(d / MASKS["pore"]) as t:
        z = len(t.pages); h, w = t.pages[0].shape[:2]
    found[name] = (z, h, w)
    print(f"{name}: {z} x {h} x {w}")
if not found:
    raise SystemExit("no sample folders found")
Z = min(v[0] for v in found.values()); Y = min(v[1] for v in found.values()); X = min(v[2] for v in found.values())
Y, X = min(Y, 700), min(X, 1700)
print(f"common analysis volume: {Z} x {Y} x {X}")

cfg = yaml.safe_load(open(a.template))
cfg["paths"]["data_root"] = str(root)
cfg["runtime"]["device"] = a.device
cfg["runtime"]["n_workers"] = a.n_workers
cfg["analysis_volume"] = {"shape_zyx": [Z, Y, X], "enforce": True}
samples = []
for name, (z, h, w) in found.items():
    y0, x0 = (h - Y) // 2, (w - X) // 2
    samples.append({"name": name, "nominal_lco_vol_fraction": SAMPLES[name], "input_dir": f"processed_{name}_segmented",
                    "masks": dict(MASKS), "slice_range": [None, None],
                    "crop": {"z": [0, Z], "y": [y0, y0 + Y], "x": [x0, x0 + X]}, "downsample": 1, "overrides": {}})
cfg["samples"] = samples
cfg["tortuosity"]["downsample"] = a.tortuosity_downsample
cfg["grains"]["downsample"] = a.grains_downsample
cfg["plotting"]["sample_colors"] = {k: v for k, v in cfg["plotting"]["sample_colors"].items()}
with open(a.out, "w") as fh:
    fh.write("# generated by make_rf_config.py - edit and re-run run_rf.ps1 -SkipConfig to keep manual changes\n")
    yaml.safe_dump(cfg, fh, sort_keys=False, allow_unicode=True)
print(f"wrote {a.out}")
